"""Ingest a real working directory into the context-hub knowledge graph.

Designed for production-scale repos:
  • Respects .gitignore and common vendor/build dirs
  • Uses os.walk with pruning (faster than blind rglob on huge trees)
  • Inverted-index-friendly node text (id, name, summary, metadata)
  • Caps function/class nodes per module to bound graph size
  • Indexes markdown/docs as Document nodes linked to nearest service

Hierarchy:
    Repository → Service → Module → Function/Class
    Repository → Document (business docs)
    Repository → Component (declared ids from code_crosswalk.yaml / components.yaml)
    Repository → Requirement/UserStory/TestCase/Epic/Term (ids found in prose)

Edges:
    CONTAINS, DOCUMENTED_BY, IMPORTS, DEPENDS_ON, RELATES_TO (doc↔service mention),
    IMPLEMENTS (Module → Component, from the crosswalk),
    RELATES_TO (artifact → id node, from a `PREFIX-Identifier` mention),
    DEPENDS_ON (TC → US → REQ, declared by a `linked_to` column),
    DEPENDS_ON (Component → Component, Term → Component, declared by a catalog),
    IMPLEMENTS (Component → Endpoint, from `components.yaml exposes:`)

The three structured passes run in a fixed order, and it is load-bearing:
crosswalk → declared catalogs (catalogs.py) → id extraction (idlinks.py) →
declared catalog edges. Declaring nodes before extraction is what stops a
`declared: False` stub being minted for an entity the corpus does declare;
emitting the typed edges after it is what lets them supersede the weaker
`RELATES_TO` mentions covering the same pair.
"""
