def _safe_id(text: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_.:/-]+", "-", text).strip("-")[:160]


def _parse_openapi(text: str) -> tuple[list[dict], list[dict]]:
    try:
        data = json.loads(text) if text.lstrip().startswith("{") else None
    except json.JSONDecodeError:
        data = None
    if data is None:
        try:
            import yaml  # type: ignore
            data = yaml.safe_load(text)
        except Exception:
            data = None
    if not isinstance(data, dict):
        return [], []
    endpoints: list[dict] = []
    schemas: list[dict] = []
    for path, ops in (data.get("paths") or {}).items():
        if not isinstance(ops, dict):
            continue
        for method, spec in ops.items():
            if method.lower() not in {"get", "post", "put", "patch", "delete", "options", "head"}:
                continue
            if not isinstance(spec, dict):
                spec = {}
            endpoints.append({
                "method": method.upper(),
                "path": str(path),
                "name": spec.get("operationId") or f"{method.upper()} {path}",
                "summary": spec.get("summary") or spec.get("description") or f"{method.upper()} {path}",
            })
    components = data.get("components") or {}
    if not isinstance(components, dict):
        components = {}
    schemas_block = components.get("schemas") or {}
    if not isinstance(schemas_block, dict):
        schemas_block = {}
    for name, spec in schemas_block.items():
        fields = []
        if isinstance(spec, dict):
            props = spec.get("properties") or {}
            if isinstance(props, dict):
                fields = list(props.keys())[:20]
        schemas.append({"name": str(name), "fields": fields})
    return endpoints, schemas


def _config_kind(path: Path) -> str | None:
    name = path.name.lower()
    if name in {"docker-compose.yml", "docker-compose.yaml", "dockerfile"}:
        return "container"
    if name.startswith((".github",)):
        return "ci"
    if path.suffix.lower() in {".sql"}:
        return "schema"
    if name in {"package.json", "pyproject.toml", "requirements.txt", "go.mod", "pom.xml", "cargo.toml"}:
        return "manifest"
    if path.suffix.lower() in {".yaml", ".yml", ".json", ".toml"}:
        if any(part.lower() in {".github", "workflows", "k8s", "helm"} for part in path.parts):
            return "infra"
    return None


def _attach_endpoint_and_schema_nodes(
    graph: Graph,
    *,
    owner_id: str,
    owner_domain: str,
    rel: Path,
    endpoints: list[dict],
    schemas: list[dict],
) -> None:
    for ep in endpoints:
        eid = f"ep:{rel}:{_safe_id(ep['method'])}:{_safe_id(ep['path'])}"
        summary = str(ep["summary"])[:240]
        graph.add_node(Node(
            eid, NodeType.ENDPOINT, str(ep["name"]), domain=owner_domain,
            summary=summary, summary_tokens=est_tokens(summary),
            metadata={"path": str(rel), "repo_path": str(rel),
                      "method": ep["method"], "endpoint_path": ep["path"]},
        ))
        graph.add_edge(Edge(EdgeType.IMPLEMENTS, owner_id, eid, source=Source.PARSED))
    for sch in schemas:
        sid = f"schema:{rel}:{_safe_id(sch['name'])}"
        summary = f"Schema {sch['name']}"
        graph.add_node(Node(
            sid, NodeType.SCHEMA, str(sch["name"]), domain=owner_domain,
            summary=summary, summary_tokens=est_tokens(summary),
            metadata={"path": str(rel), "repo_path": str(rel), "fields": sch["fields"]},
        ))
        graph.add_edge(Edge(EdgeType.USES_SCHEMA, owner_id, sid, source=Source.PARSED))


def _attach_component_nodes(
    graph: Graph,
    *,
    root: Path,
    repo_id: str,
    domain: str,
    modules_by_rel: dict[str, str],
) -> int:
    """Turn ``code_crosswalk.yaml`` into Component nodes wired to their code.

    The crosswalk is a declared bridge between two namespaces that otherwise
    never meet in the graph: the ``CMP-*`` ids the docs use and the
    ``codebase/<dir>/`` paths the modules live at.

    Edge direction follows the existing IMPLEMENTS convention (implementer →
    implemented, as Service → Endpoint elsewhere in this file): the module
    implements the component. That also makes the component reachable by an
    upward impact traversal from either end.

    A code directory with no crosswalk row gets no component and no edge. That
    silence is the point — ``sources/codebase/inventory_service/`` is
    undocumented on purpose, as a drift-detection signal.
    """
    path = identity.find_crosswalk(root)
    if path is None:
        return 0
    entries = identity.parse_crosswalk(_read(path))
    if not entries:
        return 0
    cmap = identity.ComponentMap(entries)
    rel_crosswalk = str(path.relative_to(root))

    for entry in entries:
        code_dir = f"{entry.code_path}/"
        summary = f"Component {entry.component_id}, implemented by {code_dir}"
        graph.add_node(Node(
            entry.component_id, NodeType.COMPONENT, entry.component_id, domain=domain,
            summary=summary, summary_tokens=est_tokens(summary),
            metadata={
                "component_id": entry.component_id,
                "code_path": entry.code_path,
                "path": rel_crosswalk,
                "repo_path": rel_crosswalk,
            },
        ))
        graph.add_edge(Edge(EdgeType.CONTAINS, repo_id, entry.component_id,
                            source=Source.PARSED))

    linked = 0
    for rel, mod_id in modules_by_rel.items():
        component_id = cmap.component_for_code_path(rel)
        if component_id is None:
            continue
        graph.add_edge(Edge(
            EdgeType.IMPLEMENTS, mod_id, component_id,
            attributes={"reason": "code_crosswalk"}, source=Source.PARSED,
        ))
        linked += 1
    return linked


def _id_node_index(graph: Graph) -> dict[str, str]:
    """Every id spelling already present in the graph → the node that owns it.

    Shared by the id extractor and the catalog emitter, deliberately: both must
    bind ``API-placeOrder`` to the *same* Endpoint node, and a second
    hand-rolled copy of this lookup is exactly how that invariant would rot.

    Two sources of truth. A node whose type is one an id can name is indexed by
    its own id and by any identifier its metadata declares. Endpoints are also
    indexed by ``operationId``, which is what makes ``components.yaml exposes:
    API-placeOrder`` and the OpenAPI operation one entity rather than two —
    but only when the name is unique across the corpus. An operationId claimed
    by two specs cannot be bound without guessing which was meant, so it is
    left out and mints its own node instead; the ambiguity is worth seeing.
    """
    index: dict[str, str] = {}
    endpoints_by_name: dict[str, list[str]] = {}
    id_types = set(idlinks.NODE_TYPE_BY_PREFIX.values())

    for node in graph.nodes.values():
        if node.type is NodeType.ENDPOINT:
            endpoints_by_name.setdefault(node.name.casefold(), []).append(node.id)
        if node.type not in id_types:
            continue
        index.setdefault(node.id.casefold(), node.id)
        metadata = node.metadata or {}
        for key in ("component_id", "identifier"):
            declared = metadata.get(key)
            if declared:
                index.setdefault(str(declared).casefold(), node.id)

    endpoint_prefixes = [
        p for p, t in idlinks.NODE_TYPE_BY_PREFIX.items() if t is NodeType.ENDPOINT
    ]
    for name, node_ids in endpoints_by_name.items():
        if len(node_ids) == 1:
            for prefix in endpoint_prefixes:
                index.setdefault(f"{prefix}-{name}".casefold(), node_ids[0])
    return index


def _declare_catalog_nodes(
    graph: Graph,
    *,
    root: Path,
    repo_id: str,
    domain: str,
) -> tuple[list[catalogs.Declaration], catalogs.CatalogStats]:
    """Pass A — give every declared component and term a real, *declared* node.

    This runs **before** the id extractor on purpose. ``terms.yaml`` defines
    ``TERM-DeviceFinancing`` with a name and a definition; if the extractor got
    there first it would mint a bare stub carrying ``declared: False`` and the
    summary *"not declared anywhere in this repository"* — which is simply
    false, and it corrupts the one flag the drift narrative depends on. Making
    the declared node first means the extractor *binds* to it, and
    ``declared: False`` keeps meaning what it is supposed to mean: referenced
    somewhere, defined nowhere.

    Components usually already exist, built from the crosswalk, which knows the
    code path but not the display name or the prose description. Those are
    merged in rather than replacing the node, so both halves survive.
    """
    stats = catalogs.CatalogStats()
    declarations: list[catalogs.Declaration] = []

    for filenames, collections, text_fields, ntype in (
        (catalogs.COMPONENT_FILENAMES, catalogs.COMPONENT_COLLECTIONS,
         catalogs.COMPONENT_TEXT_FIELDS, NodeType.COMPONENT),
        (catalogs.TERM_FILENAMES, catalogs.TERM_COLLECTIONS,
         catalogs.TERM_TEXT_FIELDS, NodeType.TERM),
    ):
        path = catalogs.find_catalog(root, filenames)
        if path is None:
            continue
        rel = str(path.relative_to(root))
        rows = catalogs.parse_declarations(
            _read(path), collections=collections,
            text_fields=text_fields, source_file=rel,
        )
        if not rows:
            continue
        declarations.extend(rows)
        if ntype is NodeType.COMPONENT:
            stats.components += len(rows)
        else:
            stats.terms += len(rows)

        for decl in rows:
            node = graph.nodes.get(decl.id)
            if node is None:
                summary = decl.text or f"{ntype.value} {decl.id}"
                graph.add_node(Node(
                    decl.id, ntype, decl.name or decl.id, domain=domain,
                    summary=summary, summary_tokens=est_tokens(summary),
                    metadata={
                        "identifier": decl.id, "id_prefix": idlinks.prefix_of(decl.id),
                        "declared": True, "display_name": decl.name,
                        "description": decl.text,
                        "path": rel, "repo_path": rel,
                    },
                ))
                graph.add_edge(Edge(EdgeType.CONTAINS, repo_id, decl.id,
                                    source=Source.PARSED))
                stats.created += 1
                continue

            # Merge onto whatever the crosswalk (or an earlier pass) already knew.
            if decl.name:
                node.name = decl.name
            if decl.text:
                node.summary = decl.text
                node.summary_tokens = est_tokens(decl.text)
            metadata = dict(node.metadata or {})
            metadata.update({
                "identifier": decl.id, "declared": True,
                "display_name": decl.name, "description": decl.text,
                "declared_in": rel,
            })
            node.metadata = metadata
            stats.enriched += 1

    return declarations, stats


def _attach_catalog_edges(
    graph: Graph,
    *,
    declarations: list[catalogs.Declaration],
    stats: catalogs.CatalogStats,
) -> catalogs.CatalogStats:
    """Pass B — emit the typed, directional edges the catalogs declare.

    Runs **after** the id extractor so every referenced id is guaranteed to
    have a node to point at, whether it was bound to an existing one or minted.

    Phase 4.3's de-duplication is here: a declared relation is a *statement*,
    while the extractor's ``RELATES_TO`` is only evidence that two ids appeared
    near each other. Where both exist for the same pair the weaker one is
    removed, so the graph carries one edge with the strongest available claim
    rather than a typed edge shadowed by a lateral duplicate.

    A target that resolves to no node is counted, not invented. On ``sources/``
    that count is the honest measure of dangling references in the corpus.
    """
    if not declarations:
        return stats
    index = _id_node_index(graph)

    typed: set[tuple[str, str, EdgeType]] = set()
    mention_rows: dict[frozenset[str], list[int]] = {}
    for position, edge in enumerate(graph.edges):
        typed.add((edge.src, edge.dst, edge.type))
        if edge.type is EdgeType.RELATES_TO:
            mention_rows.setdefault(frozenset((edge.src, edge.dst)), []).append(position)

    superseded: set[int] = set()
    for decl in declarations:
        src = index.get(decl.id.casefold(), decl.id)
        if src not in graph.nodes:
            continue
        for _field, etype, reason, target in decl.relations():
            dst = index.get(target.casefold())
            if dst is None or dst not in graph.nodes or dst == src:
                stats.unresolved += dst is None
                continue
            if (src, dst, etype) in typed:
                stats.duplicate += 1
                continue
            graph.add_edge(Edge(
                etype, src, dst,
                attributes={"reason": reason, "via": decl.source_file},
                confidence=Confidence.CONFIRMED, source=Source.PARSED,
            ))
            typed.add((src, dst, etype))
            for position in mention_rows.get(frozenset((src, dst)), ()):
                if position not in superseded:
                    superseded.add(position)
                    stats.replaced_mentions += 1
            stats.typed_edges += 1

    if superseded:
        graph.edges = [e for i, e in enumerate(graph.edges) if i not in superseded]
    graph.build_index()
    return stats


def _attach_id_nodes(
    graph: Graph,
    *,
    repo_id: str,
    domain: str,
    index: idlinks.IdIndex,
) -> idlinks.IdScanStats:
    """Promote every `PREFIX-Identifier` found in prose to a node, and link it.

    Three steps, in this order, because each depends on the last:

    1. **Bind or mint.** An id that already has a node uses it — ``CMP-*`` finds
       the Component the crosswalk declared, ``API-*`` finds the Endpoint
       ``_parse_openapi`` built from a matching ``operationId``. Binding is what
       makes ``components.yaml exposes: API-placeOrder`` and the OpenAPI
       operation the *same* entity. Anything unmatched is minted with
       ``declared: False``, which is a drift signal worth keeping, not a defect.
    2. **Declared links.** ``linked_to`` gives real direction, so those edges are
       laid down first and marked CONFIRMED.
    3. **Mentions.** Everything else is a lateral RELATES_TO, marked INFERRED —
       a document naming an id is evidence of a relationship, not a statement of
       one. A pair already joined by a typed edge is skipped, so the stronger
       claim always wins (this is the de-duplication Phase 4 would otherwise
       have to undo).

    Minting never invents a *declared* component: ``CMP-InventoryService``
    appears nowhere in ``sources/``, so the undocumented service stays
    unresolvable exactly as §2.8 intends.
    """
    kept = index.finalize()
    if not kept:
        return index.stats

    existing = _id_node_index(graph)

    node_for: dict[str, str] = {}
    for identifier in sorted(kept):
        bound = existing.get(identifier.casefold())
        if bound:
            node_for[identifier] = bound
            continue
        prefix = idlinks.prefix_of(identifier)
        ntype = idlinks.NODE_TYPE_BY_PREFIX.get(prefix, NodeType.DATA_ARTIFACT)
        summary = (
            f"{ntype.value} {identifier}, referenced by {len(kept[identifier])} "
            f"artifact(s); not declared anywhere in this repository"
        )
        graph.add_node(Node(
            identifier, ntype, identifier, domain=domain,
            summary=summary, summary_tokens=est_tokens(summary),
            metadata={"identifier": identifier, "id_prefix": prefix, "declared": False},
        ))
        graph.add_edge(Edge(EdgeType.CONTAINS, repo_id, identifier, source=Source.PARSED))
        node_for[identifier] = identifier
        index.stats.minted_nodes += 1

    connected: set[tuple[str, str]] = set()
    for edge in graph.edges:
        connected.add((edge.src, edge.dst))
        connected.add((edge.dst, edge.src))

    semantics = index.options.link_semantics
    for src_id, dst_id in sorted(index.links):
        src, dst = node_for.get(src_id), node_for.get(dst_id)
        if not src or not dst or src == dst or (src, dst) in connected:
            continue
        etype, reason = semantics.get(
            (idlinks.prefix_of(src_id), idlinks.prefix_of(dst_id)), idlinks.FALLBACK_LINK
        )
        graph.add_edge(Edge(
            etype, src, dst, attributes={"reason": reason, "via": "linked_to"},
            source=Source.PARSED,
        ))
        connected.add((src, dst))
        connected.add((dst, src))
        index.stats.link_edges += 1

    for identifier in sorted(kept):
        target = node_for[identifier]
        for artifact in sorted(kept[identifier]):
            if artifact == target or (artifact, target) in connected:
                continue
            graph.add_edge(Edge(
                EdgeType.RELATES_TO, artifact, target,
                attributes={"reason": "id_mention", "identifier": identifier},
                confidence=Confidence.INFERRED, source=Source.PARSED,
            ))
            connected.add((artifact, target))
            connected.add((target, artifact))
            index.stats.mention_edges += 1

    return index.stats


def ingest(
    root: Path,
    *,
    verbose: bool = False,
    include_functions: bool = True,
    max_defs_per_module: int = DEFAULT_MAX_DEFS,
    include_chunks: bool = True,
    max_chunks_per_file: int = DEFAULT_MAX_CHUNKS,
    include_docs: bool = True,
    respect_gitignore: bool = True,
    cache_dir: Path | None = None,
    include_id_links: bool = True,
    id_link_options: idlinks.IdLinkOptions | None = None,
    include_catalogs: bool = True,
) -> Graph:
    root = Path(root).resolve()
    files = list(_walk(root, respect_gitignore=respect_gitignore))
    extract_root = cache_dir or (root / ".contexthub" / "extracts")
    graph = Graph()
    # Scanned inline as files stream past so the extracted text is never all
    # held at once — only the id sets survive each file.
    id_index = idlinks.IdIndex(id_link_options) if include_id_links else None

    repo_id = f"repo:{root.name}"
    repo_readme = next((f for f in files if f.parent == root
                        and f.name.lower() in README_NAMES), None)
    repo_summary = _readme_summary(_read(repo_readme)) if repo_readme else f"Repository {root.name}"
    graph.add_node(Node(repo_id, NodeType.REPOSITORY, root.name, domain=root.name,
                        summary=repo_summary, summary_tokens=est_tokens(repo_summary),
                        metadata={"path": str(root)}))

    services = _discover_services(root, files)
    service_dirs = sorted(services.keys(), key=lambda p: len(p.parts), reverse=True)

    svc_id_by_dir: dict[Path, str] = {}
    for d, info in services.items():
        rel = "." if d == root else str(d.relative_to(root))
        svc_id = f"svc:{rel}"
        svc_id_by_dir[d] = svc_id
        readme = next((f for f in files if f.parent == d
                       and f.name.lower() in README_NAMES), None)
        summary = _readme_summary(_read(readme)) if readme else f"Service {info['name']}"
        graph.add_node(Node(
            svc_id, NodeType.SERVICE, info["name"], domain=info["name"],
            summary=summary, summary_tokens=est_tokens(summary),
            metadata={"path": rel, "repo_path": rel}))
        graph.add_edge(Edge(EdgeType.CONTAINS, repo_id, svc_id))
        if readme:
            doc_id = f"doc:{readme.relative_to(root)}"
            graph.add_node(Node(doc_id, NodeType.DOCUMENT, readme.name, domain=info["name"],
                                summary=summary, summary_tokens=est_tokens(summary),
                                metadata={"path": str(readme.relative_to(root))}))
            graph.add_edge(Edge(EdgeType.DOCUMENTED_BY, svc_id, doc_id, source=Source.PARSED))

    module_index: dict[str, str] = {}
    module_service: dict[str, str] = {}
    module_imports: dict[str, list[str]] = {}
    modules_by_rel: dict[str, str] = {}

    source_files = [f for f in files if LANG_BY_EXT.get(f.suffix) and not _is_generated(_read(f)[:600])]
    source_paths = {f.resolve() for f in source_files}
    doc_files = [
        f for f in files
        if include_docs and _is_doc_file(f, root)
        and f.name.lower() not in README_NAMES
        and f.resolve() not in source_paths
    ]

    for f in source_files:
        lang = LANG_BY_EXT[f.suffix]
        rel = f.relative_to(root)
        text = _read(f)
        if not text:
            continue
        svc_dir = _nearest_service(f, service_dirs, root)
        svc_id = svc_id_by_dir.get(svc_dir, repo_id)
        svc_name = services[svc_dir]["name"] if svc_dir in services else root.name
        if services.get(svc_dir) and services[svc_dir]["lang"] is None:
            services[svc_dir]["lang"] = lang

        mod_id = f"mod:{rel}"
        mod_summary, defs, imports = _extract(f, text)
        mod_summary = mod_summary or f"{lang} module {f.name}"
        extract_rel = _write_extract(extract_root, rel, text)
        graph.add_node(Node(mod_id, NodeType.MODULE, str(rel), domain=svc_name,
                            summary=mod_summary, summary_tokens=est_tokens(mod_summary),
                            metadata={"language": lang, "path": str(rel), "repo_path": str(rel),
                                      "loc": text.count("\n") + 1, "extension": f.suffix.lower(),
                                      "extract_path": extract_rel, "content_chars": len(text)}))
        graph.add_edge(Edge(EdgeType.CONTAINS, svc_id, mod_id))
        cfg_kind = _config_kind(f)
        if cfg_kind:
            cfg_id = f"cfg:{rel}"
            cfg_summary = f"{cfg_kind.title()} config {f.name}"
            graph.add_node(Node(
                cfg_id, NodeType.CONFIG, f.name, domain=svc_name,
                summary=cfg_summary, summary_tokens=est_tokens(cfg_summary),
                metadata={"path": str(rel), "repo_path": str(rel), "kind": cfg_kind,
                          "extract_path": extract_rel},
            ))
            graph.add_edge(Edge(EdgeType.READS_CONFIG, svc_id, cfg_id, source=Source.PARSED))

        stem = str(rel.with_suffix(""))
        module_index[stem] = mod_id
        module_index[stem.replace("/", ".")] = mod_id
        module_index.setdefault(f.stem, mod_id)
        module_service[mod_id] = svc_id
        module_imports[mod_id] = imports
        modules_by_rel[str(rel)] = mod_id
        if id_index is not None:
            id_index.scan(mod_id, text)

        if include_functions:
            for kind, name, summary, start, end in defs[:max_defs_per_module]:
                fn_id = f"fn:{rel}:{name}"
                ntype = NodeType.CLASS if kind == "Class" else NodeType.FUNCTION
                graph.add_node(Node(fn_id, ntype, name, domain=svc_name,
                                    summary=summary, summary_tokens=est_tokens(summary),
                                    metadata={
                                        "file": str(rel), "path": str(rel),
                                        "start_line": start, "end_line": end,
                                    }))
                graph.add_edge(Edge(EdgeType.CONTAINS, mod_id, fn_id))

        if include_chunks:
            _add_chunk_nodes(
                graph,
                parent_id=mod_id,
                rel=rel,
                text=text,
                domain=svc_name,
                extract_rel=extract_rel,
                language=lang,
                max_chunks=max_chunks_per_file,
            )

    for f in doc_files:
        rel = f.relative_to(root)
        text = extract_text(f)
        if not text or len(text.strip()) < 10:
            continue
        svc_dir = _nearest_service(f, service_dirs, root)
        svc_name = services[svc_dir]["name"] if svc_dir in services else root.name
        doc_id = f"doc:{rel}"
        if doc_id in graph.nodes:
            continue
        extract_rel = _write_extract(extract_root, rel, text)
        summary = _doc_summary(text)
        graph.add_node(Node(
            doc_id, NodeType.DOCUMENT, f.name, domain=svc_name,
            summary=summary, summary_tokens=est_tokens(summary),
            metadata={
                "path": str(rel), "repo_path": str(rel),
                "extension": f.suffix.lower(),
                "extract_path": extract_rel,
                "content_chars": len(text),
            },
        ))
        svc_id = svc_id_by_dir.get(svc_dir, repo_id)
        graph.add_edge(Edge(EdgeType.DOCUMENTED_BY, svc_id, doc_id, source=Source.PARSED))
        graph.add_edge(Edge(EdgeType.CONTAINS, repo_id, doc_id))
        if id_index is not None:
            id_index.scan(doc_id, text, tabular=f.suffix.lower() in TABULAR_EXTENSIONS)
        if include_chunks:
            _add_chunk_nodes(
                graph,
                parent_id=doc_id,
                rel=rel,
                text=text,
                domain=svc_name,
                extract_rel=extract_rel,
                max_chunks=max_chunks_per_file,
            )
        endpoints, schemas = ([], [])
        if "openapi" in f.name.lower() or f.suffix.lower() in {".yaml", ".yml", ".json"}:
            endpoints, schemas = _parse_openapi(text)
        if endpoints or schemas:
            md = dict(graph.nodes[doc_id].metadata or {})
            md["doc_type"] = md.get("doc_type") or "openapi"
            graph.nodes[doc_id].metadata = md
            _attach_endpoint_and_schema_nodes(
                graph, owner_id=svc_id, owner_domain=svc_name, rel=rel,
                endpoints=endpoints, schemas=schemas,
            )
        cfg_kind = _config_kind(f)
        if cfg_kind:
            cfg_id = f"cfg:{rel}"
            cfg_summary = f"{cfg_kind.title()} config {f.name}"
            graph.add_node(Node(
                cfg_id, NodeType.CONFIG, f.name, domain=svc_name,
                summary=cfg_summary, summary_tokens=est_tokens(cfg_summary),
                metadata={"path": str(rel), "repo_path": str(rel), "kind": cfg_kind,
                          "extract_path": extract_rel},
            ))
            graph.add_edge(Edge(EdgeType.READS_CONFIG, svc_id, cfg_id, source=Source.PARSED))

    dep_pairs: set[tuple[str, str]] = set()
    for mod_id, imports in module_imports.items():
        src_svc = module_service[mod_id]
        for imp in imports:
            target = _resolve_import(imp, mod_id, module_index)
            if not target or target == mod_id:
                continue
            graph.add_edge(Edge(EdgeType.IMPORTS, mod_id, target, source=Source.STATIC))
            dst_svc = module_service.get(target)
            if dst_svc and dst_svc != src_svc and (src_svc, dst_svc) not in dep_pairs:
                dep_pairs.add((src_svc, dst_svc))
                graph.add_edge(Edge(EdgeType.DEPENDS_ON, src_svc, dst_svc,
                                    attributes={"reason": "import"}, source=Source.STATIC))

    linked_components = _attach_component_nodes(
        graph, root=root, repo_id=repo_id, domain=root.name,
        modules_by_rel=modules_by_rel,
    )

    # Pass A: declared components and terms become real nodes *before* the
    # extractor runs, so it binds to them instead of minting `declared: False`
    # stubs for entities this repo demonstrably declares.
    declarations: list[catalogs.Declaration] = []
    catalog_stats = None
    if include_catalogs:
        declarations, catalog_stats = _declare_catalog_nodes(
            graph, root=root, repo_id=repo_id, domain=root.name,
        )

    id_stats = None
    if id_index is not None:
        # After the components exist, so `CMP-*` binds to them instead of
        # minting a rival node for the same entity.
        id_stats = _attach_id_nodes(
            graph, repo_id=repo_id, domain=root.name, index=id_index,
        )

    # Pass B: the declared edges, last, so every id they reference already has
    # a node — bound or minted — and the de-duplication can see every mention.
    if catalog_stats is not None:
        _attach_catalog_edges(graph, declarations=declarations, stats=catalog_stats)

    # workflow-compiler edit: node ids and path metadata are OS-independent.
    _normalise_posix(graph)

    graph.build_index()
    if verbose:
        extra = f", {linked_components} modules bridged to components" if linked_components else ""
        if id_stats and id_stats.ids_kept:
            extra += f", {id_stats.summary()}"
        if catalog_stats and catalog_stats.typed_edges:
            extra += f", {catalog_stats.summary()}"
        print(f"  scanned {len(files)} files, {len(source_files)} source, "
              f"{len(doc_files)} docs under {root}{extra}")
    return graph


_PATH_METADATA_KEYS = ("path", "repo_path", "file", "extract_path", "declared_in")


def _posix(value: str) -> str:
    return value.replace("\\", "/")


def _normalise_posix(graph: Graph) -> None:
    """Rewrite node ids, module names and path metadata to ``/`` separators.

    workflow-compiler edit. Upstream builds ids like ``mod:src\\pkg\\mod.py`` on
    Windows, which makes a graph built on one OS undereferenceable on another
    and makes ids differ between developers' machines. Ids are rewritten in
    place, edges re-pointed, and the adjacency index rebuilt by the caller.
    """
    renames: dict[str, str] = {}
    for old_id, node in list(graph.nodes.items()):
        new_id = _posix(old_id)
        md = node.metadata
        if md:
            for key in _PATH_METADATA_KEYS:
                val = md.get(key)
                if isinstance(val, str) and "\\" in val:
                    md[key] = _posix(val)
        if "\\" in node.name and node.type in (NodeType.MODULE, NodeType.CHUNK,
                                               NodeType.FUNCTION, NodeType.CLASS):
            node.name = _posix(node.name)
        if new_id != old_id:
            renames[old_id] = new_id
            node.id = new_id
    if not renames:
        return
    for old_id, new_id in renames.items():
        node = graph.nodes.pop(old_id)
        graph.nodes.setdefault(new_id, node)
    for edge in graph.edges:
        if edge.src in renames:
            edge.src = renames[edge.src]
        if edge.dst in renames:
            edge.dst = renames[edge.dst]
    graph._indexed = False


def _resolve_import(imp: str, src_mod_id: str, index: dict[str, str]) -> str | None:
    if imp.startswith("."):
        src_rel = Path(src_mod_id[len("mod:"):])
        base = src_rel.parent
        up = len(imp) - len(imp.lstrip("."))
        for _ in range(max(up - 1, 0)):
            base = base.parent
        target = (base / imp.lstrip(".").replace(".", "/")).as_posix()
        return index.get(target) or index.get(Path(target).name)
    candidates = [imp, imp.replace(".", "/"), imp.split(".")[-1], imp.split("/")[-1]]
    for c in candidates:
        if c in index:
            return index[c]
    return None
