def _load_gitignore(root: Path) -> list[str]:
    patterns: list[str] = []
    gi = root / ".gitignore"
    if not gi.is_file():
        return patterns
    for line in gi.read_text(encoding="utf-8", errors="ignore").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            patterns.append(line)
    return patterns


def _ignored_path(rel: Path, patterns: list[str]) -> bool:
    s = rel.as_posix()
    for pat in patterns:
        if fnmatch.fnmatch(s, pat) or fnmatch.fnmatch(s, pat.lstrip("/")):
            return True
        if pat.endswith("/") and s.startswith(pat.rstrip("/")):
            return True
    return False


def _walk(root: Path, *, respect_gitignore: bool = True):
    patterns = _load_gitignore(root) if respect_gitignore else []
    for dirpath, dirnames, filenames in os.walk(root):
        rel_dir = Path(dirpath).relative_to(root)
        at_root = rel_dir == Path(".")
        dirnames[:] = sorted(
            d for d in dirnames
            if d not in IGNORE_DIRS
            and not (at_root and d in ROOT_ONLY_IGNORE_DIRS)
            and not _ignored_path(rel_dir / d, patterns)
        )
        for name in sorted(filenames):
            path = Path(dirpath) / name
            rel = path.relative_to(root)
            if _ignored_path(rel, patterns):
                continue
            if path.suffix.lower() in SKIP_EXTENSIONS:
                continue
            yield path


def _read(path: Path) -> str:
    try:
        if path.stat().st_size > MAX_FILE_BYTES:
            return ""
        return path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return ""


def _is_generated(text: str) -> bool:
    head = text[:500].lower()
    return any(m in head for m in GENERATED_MARKERS)


def _readme_summary(text: str, limit: int = 240) -> str:
    for line in text.splitlines():
        s = line.strip().lstrip("#").strip()
        if s and not s.startswith(("![", "[!", "---", "===", "```")):
            return s[:limit]
    return ""


def _doc_summary(text: str, limit: int = 300) -> str:
    for line in text.splitlines():
        s = line.strip().lstrip("#").strip()
        if len(s) > 20 and not s.startswith(("![", "```", "---")):
            return s[:limit]
    return text[:limit].replace("\n", " ")


def _python_defs(text: str) -> tuple[str, list[tuple[str, str, str, int, int]], list[str]]:
    """Return (module_summary, defs, imports).

    Each def is (kind, name, summary, start_line, end_line) with 1-indexed lines.
    """
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return "", [], []
    mod_doc = (ast.get_docstring(tree) or "").splitlines()
    mod_summary = mod_doc[0] if mod_doc else ""
    defs: list[tuple[str, str, str, int, int]] = []
    imports: list[str] = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            doc = (ast.get_docstring(node) or "").splitlines()
            args = ", ".join(a.arg for a in node.args.args)
            summary = doc[0] if doc else f"def {node.name}({args})"
            start = int(node.lineno)
            if getattr(node, "decorator_list", None):
                start = min(start, min(d.lineno for d in node.decorator_list))
            end = int(getattr(node, "end_lineno", None) or start)
            defs.append(("Function", node.name, summary, start, end))
        elif isinstance(node, ast.ClassDef):
            doc = (ast.get_docstring(node) or "").splitlines()
            summary = doc[0] if doc else f"class {node.name}"
            start = int(node.lineno)
            if getattr(node, "decorator_list", None):
                start = min(start, min(d.lineno for d in node.decorator_list))
            end = int(getattr(node, "end_lineno", None) or start)
            defs.append(("Class", node.name, summary, start, end))
        elif isinstance(node, ast.Import):
            imports.extend(a.name for a in node.names)
        elif isinstance(node, ast.ImportFrom):
            if node.module and node.level == 0:
                imports.append(node.module)
            elif node.module:
                imports.append("." * node.level + node.module)
    return mod_summary, defs, imports


_RE_DEFS = re.compile(
    r"^\s*(?:export\s+)?(?:public\s+|private\s+|protected\s+|static\s+|async\s+)*"
    r"(?:function|func|def|class|interface|type)\s+([A-Za-z_]\w*)",
    re.MULTILINE,
)
_RE_ARROW = re.compile(r"^\s*(?:export\s+)?const\s+([A-Za-z_]\w*)\s*=\s*(?:async\s*)?\(", re.MULTILINE)
_RE_IMPORT = re.compile(
    r"""(?:import\s+[^'"\n]*from\s+['"]([^'"]+)['"])"""
    r"""|(?:require\(\s*['"]([^'"]+)['"]\s*\))"""
    r"""|(?:import\s+([\w.]+)\s*;)"""
    r"""|(?:^\s*['"]([\w./-]+)['"]\s*$)""",
    re.MULTILINE,
)


def _regex_defs(text: str) -> tuple[str, list[tuple[str, str, str, int, int]], list[str]]:
    defs: list[tuple[str, str, str, int, int]] = []
    for m in _RE_DEFS.finditer(text):
        start = text.count("\n", 0, m.start()) + 1
        end = text.count("\n", 0, m.end()) + 1
        defs.append(("Function", m.group(1), f"{m.group(0).strip()}", start, end))
    for m in _RE_ARROW.finditer(text):
        start = text.count("\n", 0, m.start()) + 1
        end = text.count("\n", 0, m.end()) + 1
        defs.append(("Function", m.group(1), f"const {m.group(1)} = (...)", start, end))
    imports = [g for m in _RE_IMPORT.finditer(text) for g in m.groups() if g]
    return "", defs, imports


def _extract(path: Path, text: str):
    if path.suffix == ".py":
        return _python_defs(text)
    return _regex_defs(text)


def _add_chunk_nodes(
    graph: Graph,
    *,
    parent_id: str,
    rel: Path,
    text: str,
    domain: str,
    extract_rel: str,
    language: str | None = None,
    max_chunks: int = DEFAULT_MAX_CHUNKS,
) -> int:
    """Attach Chunk children + NEXT edges under a Module/Document parent."""
    spans = chunk_file(rel, text, max_chunks=max_chunks)
    if not spans:
        return 0
    prev_id: str | None = None
    for idx, span in enumerate(spans):
        chunk_id = f"chk:{rel}:{idx:03d}"
        name = span.symbol or f"{rel.name}:{span.start_line}-{span.end_line}"
        summary = span.summary or f"lines {span.start_line}-{span.end_line}"
        md: dict = {
            "path": str(rel),
            "repo_path": str(rel),
            "file": str(rel),
            "extract_path": extract_rel,
            "start_line": span.start_line,
            "end_line": span.end_line,
            "chunk_index": idx,
            "kind": span.kind,
            "parent_id": parent_id,
            "extension": rel.suffix.lower(),
        }
        if language:
            md["language"] = language
        if span.symbol:
            md["symbol"] = span.symbol
        graph.add_node(Node(
            chunk_id, NodeType.CHUNK, name, domain=domain,
            summary=summary, summary_tokens=est_tokens(summary),
            metadata=md,
        ))
        graph.add_edge(Edge(EdgeType.CONTAINS, parent_id, chunk_id, source=Source.PARSED))
        if prev_id:
            graph.add_edge(Edge(
                EdgeType.NEXT, prev_id, chunk_id,
                attributes={"order": idx},
                source=Source.PARSED,
            ))
        # Link symbol chunk to matching Function/Class node when present.
        if span.symbol:
            fn_id = f"fn:{rel}:{span.symbol}"
            if fn_id in graph.nodes:
                graph.add_edge(Edge(
                    EdgeType.RELATES_TO, fn_id, chunk_id,
                    attributes={"reason": "symbol_span"},
                    source=Source.PARSED,
                ))
        prev_id = chunk_id
    return len(spans)


def _discover_services(root: Path, files: list[Path]) -> dict[Path, dict]:
    services: dict[Path, dict] = {}
    for f in files:
        if f.name in MANIFESTS:
            d = f.parent
            services.setdefault(d, {"name": d.name if d != root else root.name,
                                    "lang": None, "readme": None})
    if not services:
        for f in files:
            rel = f.relative_to(root)
            if len(rel.parts) >= 2 and rel.parts[0].lower() in SERVICE_HINT_DIRS:
                d = root / rel.parts[0] / rel.parts[1]
                services.setdefault(d, {"name": d.name, "lang": None, "readme": None})
    if not services:
        services[root] = {"name": root.name, "lang": None, "readme": None}
    return services


def _nearest_service(path: Path, service_dirs: list[Path], root: Path) -> Path:
    best = root
    best_len = -1
    for d in service_dirs:
        try:
            path.relative_to(d)
        except ValueError:
            continue
        if len(d.parts) > best_len:
            best, best_len = d, len(d.parts)
    return best


