def _write_extract(cache_dir: Path, rel: Path, text: str) -> str:
    """Persist extracted text; return path relative to cache_dir parent (.contexthub)."""
    cache_dir.mkdir(parents=True, exist_ok=True)
    safe = rel.as_posix().replace("/", "__")
    out = cache_dir / f"{safe}.txt"
    out.write_text(text, encoding="utf-8")
    return str(out.relative_to(cache_dir.parent))


